import type { Category } from '../game/types'

function category(
  id: string,
  title: string,
  emoji: string,
  description: string,
  cards: readonly (readonly [title: string, emoji: string])[],
): Category {
  return {
    id, title, emoji, description,
    items: cards.map(([cardTitle, cardEmoji]) => ({
      id: cardTitle.normalize('NFKD').replace(/\p{M}/gu, '').toLowerCase()
        .replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''),
      title: cardTitle,
      emoji: cardEmoji,
    })),
  }
}

